"""Port Protocols — dependency-inversion boundaries.

Adapters live in robomind.llm, robomind.ui.voice, robomind.ui, robomind.memory.
Core code depends on these Protocols only, never on concrete adapters.
"""
from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Any, Literal, Protocol, runtime_checkable

from .models import Episode, Fact, Rule, ToolResult


@runtime_checkable
class Renderer(Protocol):
    def banner(self, compact: bool = True) -> None: ...
    def stage(self, name: str) -> AbstractContextManager[None]: ...
    def info(self, msg: str) -> None: ...
    def warn(self, msg: str) -> None: ...
    def error(self, msg: str) -> None: ...
    def success(self, msg: str) -> None: ...
    def result(self, title: str, lines: list[str]) -> None: ...
    def clear(self) -> None: ...


@runtime_checkable
class Voice(Protocol):
    def speak(self, text: str) -> None: ...
    def stop(self) -> None: ...
    def is_speaking(self) -> bool: ...
    def is_available(self) -> bool: ...


@runtime_checkable
class LLM(Protocol):
    def complete(
        self,
        prompt: str,
        *,
        system: str | None = None,
        max_tokens: int = 256,
        temperature: float = 0.2,
    ) -> str: ...
    def is_available(self) -> bool: ...
    def close(self) -> None: ...


@runtime_checkable
class MemoryStore(Protocol):
    def insert_fact(self, fact: Fact) -> int: ...
    def search_facts(self, query: str, limit: int = 10) -> list[Fact]: ...
    def insert_episode(self, ep: Episode) -> int: ...
    def search_episodes(self, query: str, limit: int = 10) -> list[Episode]: ...
    def get_rule(self, name: str) -> Rule | None: ...
    def upsert_rule(self, rule: Rule) -> int: ...
    def update_rule_stats(self, rule_id: int, hit: bool, win: bool) -> None: ...
    def close(self) -> None: ...


@runtime_checkable
class Tool(Protocol):
    name: str
    args_schema: dict[str, Any]
    output_schema: dict[str, Any]
    safety_class: Literal["read", "compute", "write", "hardware"]
    def run(self, **kwargs: Any) -> ToolResult: ...